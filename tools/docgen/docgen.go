// marker starts every generated page, so stale ones can be told from hand-written ones.
const marker = "<!-- Generated by `make docs-gen` from the code. Do not edit: change the code and regenerate. -->"

// base is where the docs are served; links between pages need it.
const base = "/docs"

// groups sort node types as the editor's palette does: triggers apart, then by the first
// part of their name.
var groups = []struct{ dir, label, prefix string }{
	{"triggers", "Triggers", ""},
	{"polymarket", "Polymarket", "polymarket"},
	{"logic", "Logic", "logic"},
	{"transform", "Transform", "transform"},
	{"output", "Output", "output"},
	{"telegram", "Telegram", "telegram"},
	{"code", "Code", "code"},
	{"trading", "Trading", "trading"},
}

// Pages are generated files by path, relative to the reference directory.
type Pages map[string]string

// Generate writes the reference: one page per node type, an overview of them, the
// settings and the credential types.
func Generate(nodes []engine.TypeInfo, credTypes []engine.CredentialType, specs []settings.Spec) (Pages, error) {
	pages := Pages{}

	if err := nodePages(pages, nodes, credTypes); err != nil {
		return nil, err
	}

	pages["settings.md"] = settingsPage(specs)
	pages["credential-types.md"] = credentialTypesPage(credTypes, nodes)
	pages["code-types.md"] = codeTypesPage(tscompiler.Declarations(nodes))

	return pages, nil
}

// TypeFiles are the declarations of @polythought/sdk that the code generates, by name,
// for the SDK's types directory. sdk.d.ts is tsc's.
func TypeFiles(nodes []engine.TypeInfo) map[string]string {
	out := map[string]string{}

	for _, f := range tscompiler.Declarations(nodes) {
		if f.Path != "sdk.d.ts" {
			out[f.Path] = f.Content
		}
	}

	return out
}

// codeTypesPage publishes the declarations code is written against.
func codeTypesPage(files []ports.CodeFile) string {
	var b strings.Builder

	frontmatter(&b, "Types for code",
		"The TypeScript types code is written against: the SDK's, and every node's settings and items.", 0)

	b.WriteString("Code imports everything from `@polythought/sdk`: the SDK's functions and types, and the " +
		"types of every node's settings and items, named after its type: `polymarket.markets` gives " +
		"`PolymarketMarketsSettings` and `PolymarketMarketsItem`.\n\n" +
		"```ts\nimport { dec } from \"@polythought/sdk\"\nimport type { Context, PolymarketMarketsItem } from \"@polythought/sdk\"\n```\n\n" +
		"Decimals are `DecimalText` and times `TimeText`: text, so they stay exact. `NodeTypes` names " +
		"every node type's settings and items, whether it is a trigger, and its inputs and outputs, which " +
		"[workflow code](/docs/guides/workflow-code/) is typed by; a node that passes on what it receives " +
		"says `\"received\"`.\n")

	for _, part := range []struct{ title, file string }{{"Node types", "nodes.d.ts"}, {"The SDK", "sdk.d.ts"}} {
		for _, f := range files {
			if f.Path == part.file {
				fmt.Fprintf(&b, "\n## %s\n\n`%s`\n\n```ts\n%s```\n", part.title, f.Path, f.Content)
			}
		}
	}

	return b.String()
}

func groupOf(t engine.TypeInfo) (dir, label string, ok bool) {
	for _, g := range groups {
		if t.Trigger && g.prefix == "" || !t.Trigger && g.prefix != "" && strings.HasPrefix(t.Name, g.prefix+".") {
			return g.dir, g.label, true
		}
	}

	return "", "", false
}

// slug is a node's page name: the last part of its type name, in kebab case.
func slug(name string) string {
	last := name[strings.LastIndex(name, ".")+1:]

	var b strings.Builder

	for i, r := range last {
		if r >= 'A' && r <= 'Z' {
			if i > 0 {
				b.WriteByte('-')
			}

			r += 'a' - 'A'
		}

		b.WriteRune(r)
	}

	return b.String()
}

// NodePath is a node's page, relative to the reference directory.
func NodePath(t engine.TypeInfo) (string, bool) {
	dir, _, ok := groupOf(t)
	if !ok {
		return "", false
	}

	return "nodes/" + dir + "/" + slug(t.Name) + ".md", true
}

func link(path string) string {
	return base + "/reference/" + strings.TrimSuffix(path, ".md") + "/"
}

func nodePages(pages Pages, nodes []engine.TypeInfo, credTypes []engine.CredentialType) error {
	var overview strings.Builder

	frontmatter(&overview, "Nodes", "Every node you can place in a workflow, and what it does.", 0)
	overview.WriteString("Each node has a page with its settings. In the editor, the node list on the left " +
		"holds them all, grouped the same way. How items flow between them is in " +
		"[Concepts](" + base + "/guides/concepts/).\n")

	for _, g := range groups {
		var members []engine.TypeInfo

		for _, t := range nodes {
			if dir, _, ok := groupOf(t); ok && dir == g.dir {
				members = append(members, t)
			}
		}

		if len(members) == 0 {
			continue
		}

		fmt.Fprintf(&overview, "\n## %s\n\n| Node | Type | What it does |\n|---|---|---|\n", g.label)

		for i, t := range members {
			path, _ := NodePath(t)
			pages[path] = nodePage(t, i+1, credTypes)

			fmt.Fprintf(&overview, "| [%s](%s) | `%s` | %s |\n", cell(t.Label), link(path), t.Name, cell(firstSentence(t.Description)))
		}
	}

	for _, t := range nodes {
		if _, ok := NodePath(t); !ok {
			return fmt.Errorf("docgen: node type %q fits no group; add one to the groups list", t.Name)
		}
	}

	pages["nodes.md"] = overview.String()

	return nil
}

func nodePage(t engine.TypeInfo, order int, credTypes []engine.CredentialType) string {
	var b strings.Builder

	frontmatter(&b, t.Label, firstSentence(t.Description), order)

	if t.Description != "" {
		b.WriteString(prose(t.Description) + "\n\n")
	}

	kind := "Node"
	if t.Trigger {
		kind = "Trigger: starts executions"
	}

	fmt.Fprintf(&b, "| | |\n|---|---|\n| Type | `%s` |\n| Kind | %s |\n", t.Name, kind)

	if !t.Trigger {
		fmt.Fprintf(&b, "| Inputs | %s |\n", portList(t.Inputs))
	}

	outputs := portList(t.Outputs)
	if t.OutputsParam != "" {
		outputs += ", and one per value of " + paramLabel(t.NodeType, t.OutputsParam)
	}

	fmt.Fprintf(&b, "| Outputs | %s |\n", outputs)

	if !t.Trigger {
		b.WriteString("\nItems that fail stop the execution, unless **Continue on failure** is on: then " +
			"they leave on the `error` port instead.\n")
	}

	if len(t.Params) == 0 {
		b.WriteString("\n## Settings\n\nNone.\n")
		writeItems(&b, t.NodeType)

		return b.String()
	}

	b.WriteString("\n## Settings\n\n| Setting | Kind | Required | Default | Description |\n|---|---|---|---|---|\n")

	for _, p := range t.Params {
		writeParamRow(&b, p, credTypes)
	}

	// A table's columns, each like a setting of every row.
	for _, p := range t.Params {
		if p.Kind != engine.ParamTable {
			continue
		}

		fmt.Fprintf(&b, "\n### %s columns\n\nEach row of **%s** has these cells.", labelOf(p), labelOf(p))

		if !t.Trigger { // a trigger's settings take no expressions at all
			fmt.Fprintf(&b, " Only the whole table takes an [expression](%s/guides/expressions/), not its cells.", base)
		}

		b.WriteString("\n\n| Column | Kind | Required | Default | Description |\n|---|---|---|---|---|\n")

		for _, c := range p.Columns {
			writeParamRow(&b, c, credTypes)
		}
	}

	for _, p := range t.Params {
		if starter, ok := p.Default.(string); ok && p.Kind == engine.ParamCode {
			fmt.Fprintf(&b, "\n## Starter code\n\nWhat **%s** holds until you change it:\n\n```ts\n%s```\n", p.Label, starter)
		}
	}

	writeItems(&b, t.NodeType)

	return b.String()
}

// writeItems says what the node emits, with every field, nested ones as paths.
func writeItems(b *strings.Builder, t engine.NodeType) {
	it := t.Items
	if it == nil {
		return
	}

	b.WriteString("\n## Items\n\n")

	switch {
	case it.Passed && len(it.Fields) == 0:
		b.WriteString("The items it receives, passed on as they are.\n")
		return
	case it.Passed:
		b.WriteString("The items it receives, passed on with these fields added. Decimals are text, so they " +
			"stay exact; times are RFC 3339 text.\n\n| Field | Kind | Description |\n|---|---|---|\n")
		writeFields(b, it.Fields, "")

		return
	case it.Picked != "":
		fmt.Fprintf(b, "The items it receives, with only the fields %s names.\n", paramLabel(t, it.Picked))
		return
	case len(it.Fields) == 0:
		b.WriteString("Empty: items with no fields.\n")
		return
	}

	b.WriteString("Each item has these fields. Decimals are text, so they stay exact; times are RFC 3339 text.\n\n" +
		"| Field | Kind | Description |\n|---|---|---|\n")

	writeFields(b, it.Fields, "")
}

func writeFields(b *strings.Builder, fields []engine.Field, prefix string) {
	for _, f := range fields {
		path := prefix + f.Name
		fmt.Fprintf(b, "| `%s` | %s | %s |\n", path, fieldKind(f), cell(f.Description))

		switch {
		case f.Kind == engine.FieldObject:
			writeFields(b, f.Fields, path+".")
		case f.Kind == engine.FieldList && f.Of != nil && f.Of.Kind == engine.FieldObject:
			writeFields(b, f.Of.Fields, path+"[].")
		}
	}
}

// fieldKind names a field's kind for people: "text, one of `buy`, `sell`; or null".
func fieldKind(f engine.Field) string {
	kind := kindName(f.Kind)

	switch {
	case f.Kind == engine.FieldList && f.Of != nil && f.Of.Kind == engine.FieldObject:
		kind = "list of objects"
	case f.Kind == engine.FieldList && f.Of != nil:
		kind = "list of " + kindName(f.Of.Kind)
	}

	if len(f.Options) > 0 {
		kind += ", one of " + codes(f.Options)
	}

	if f.Nullable {
		kind += "; or null"
	}

	if f.Optional {
		kind += "; not always there"
	}

	return kind
}

// fieldNote says a param names fields of the items, which saving checks.
func fieldNote(p engine.ParamSpec) string {
	what := "Names a field of the items it receives"
	if p.Kind == engine.ParamList {
		what = "Each names a field of the items it receives"
	}

	if len(p.FieldKinds) > 0 {
		kinds := make([]string, len(p.FieldKinds))
		for i, k := range p.FieldKinds {
			kinds[i] = kindName(k)
		}

		what += ", a " + strings.Join(kinds, " or ") + " one"
	}

	return what + "; saving checks the items have it."
}

// writeParamRow writes a row of a settings table, or of a table's columns.
func writeParamRow(b *strings.Builder, p engine.ParamSpec, credTypes []engine.CredentialType) {
	required := "no"
	if p.Required {
		required = "yes"
	}

	notes := []string{p.Description}
	if len(p.Options) > 0 {
		notes = append(notes, "One of "+codes(p.Options)+".")
	}

	if p.Field {
		notes = append(notes, fieldNote(p))
	}

	if p.Personal() {
		notes = append(notes, "Personal: sharing the workflow leaves it out.")
	}

	def := defaultOf(p.Default)
	if p.Kind == engine.ParamCode && p.Default != nil {
		def = "a starter, below"
	}

	fmt.Fprintf(b, "| %s (`%s`) | %s | %s | %s | %s |\n",
		cell(labelOf(p)), p.Name, paramKind(p, credTypes), required, def, cell(strings.Join(nonEmpty(notes), " ")))
}

func labelOf(p engine.ParamSpec) string {
	if p.Label == "" {
		return p.Name
	}

	return p.Label
}

func kindName(k engine.FieldKind) string {
	switch k {
	case engine.FieldBool:
		return "true or false"
	case engine.FieldAny:
		return "anything"
	default:
		return string(k)
	}
}

func paramKind(p engine.ParamSpec, credTypes []engine.CredentialType) string {
	switch p.Kind {
	case engine.ParamString:
		if p.Numbers {
			return "text or a number"
		}

		return "text"
	case engine.ParamNumber:
		return "whole number"
	case engine.ParamDecimal:
		return "number"
	case engine.ParamBool:
		return "true or false"
	case engine.ParamList:
		return "list of text"
	case engine.ParamDuration:
		return "duration, e.g. `30s`, `5m`, `1h`"
	case engine.ParamWallet:
		return "one of your [wallets](" + base + "/guides/concepts/#wallets)"
	case engine.ParamTokens:
		return "list of token IDs"
	case engine.ParamAddress:
		return "address: `0x` and 40 hex digits"
	case engine.ParamTable:
		return "table, its columns below"
	case engine.ParamCode:
		return "TypeScript; see [Code nodes](" + base + "/guides/code/)"
	case engine.ParamCredential:
		label := p.CredentialType

		for _, ct := range credTypes {
			if ct.Name == p.CredentialType {
				label = ct.Label
			}
		}

		return fmt.Sprintf("one of your credentials: [%s](%s#%s)", label, link("credential-types.md"), anchor(label))
	}

	return string(p.Kind)
}

func settingsPage(specs []settings.Spec) string {
	var b strings.Builder

	frontmatter(&b, "Settings", "Every setting of the instance, with its default and environment variable.", 0)
	b.WriteString("Admins change these on **Admin → Config** while the server runs. A setting set by its " +
		"environment variable, or in the config file under its key, cannot be changed there: the variable, " +
		"then the file, wins. How they fit together is in [Configuration](" + base + "/self-hosting/configuration/).\n")

	var group string

	for _, s := range specs {
		if s.Group != group {
			group = s.Group
			fmt.Fprintf(&b, "\n## %s\n", group)
		}

		applies := "at once"
		if s.Apply == settings.ApplyRestart {
			applies = "after a restart"
		}

		fmt.Fprintf(&b, "\n### %s\n\n%s\n\n| | |\n|---|---|\n| Key | `%s` |\n| Environment variable | `%s` |\n| Kind | %s |\n| Default | %s |\n| Applies | %s |\n",
			prose(s.Label), prose(s.Description), s.Key, s.EnvName(), settingKind(s), settingDefault(s), applies)
	}

	return b.String()
}

func settingKind(s settings.Spec) string {
	switch s.Kind {
	case settings.KindInt:
		return "whole number"
	case settings.KindBool:
		return "`true` or `false`"
	case settings.KindDuration:
		return "duration, e.g. `30s`, `5m`, `168h`"
	case settings.KindEnum:
		return "one of " + codes(s.Options)
	case settings.KindList:
		return "list; in the environment, separated by commas"
	case settings.KindString:
		if s.Secret {
			return "text, secret: stored encrypted and never shown"
		}
	}

	return "text"
}

func settingDefault(s settings.Spec) string {
	switch v := s.Default.(type) {
	case time.Duration:
		return "`" + settings.FormatDuration(v) + "`"
	case []string:
		if len(v) == 0 {
			return "empty"
		}

		return codes(v)
	case string:
		if v == "" {
			return "empty"
		}
	}

	return fmt.Sprintf("`%v`", s.Default)
}

func credentialTypesPage(credTypes []engine.CredentialType, nodes []engine.TypeInfo) string {
	var b strings.Builder

	frontmatter(&b, "Credential types", "The kinds of credential nodes can use, and their fields.", 0)
	b.WriteString("Credentials are kept on the **Credentials** page; see [Credentials](" + base +
		"/guides/credentials/). Secret fields are stored encrypted and never shown again.\n")

	for _, ct := range credTypes {
		fmt.Fprintf(&b, "\n## %s\n\n%s\n\nType `%s`.", prose(ct.Label), prose(ct.Description), ct.Name)

		if ct.Test != nil {
			b.WriteString(" It can be tested from the Credentials page.")
		}

		b.WriteString("\n\n| Field | Required | Secret | Description |\n|---|---|---|---|\n")

		for _, f := range ct.Fields {
			fmt.Fprintf(&b, "| %s (`%s`) | %s | %s | %s |\n", cell(f.Label), f.Name, yesNo(f.Required), yesNo(f.Secret), cell(f.Description))
		}

		var users []string

		for _, t := range nodes {
			for _, p := range t.Params {
				if p.Kind == engine.ParamCredential && p.CredentialType == ct.Name {
					path, _ := NodePath(t)
					users = append(users, fmt.Sprintf("[%s](%s)", t.Label, link(path)))
				}
			}
		}

		if len(users) > 0 {
			fmt.Fprintf(&b, "\nUsed by: %s.\n", strings.Join(slices.Compact(users), ", "))
		}
	}

	return b.String()
}

func frontmatter(b *strings.Builder, title, description string, order int) {
	b.WriteString("---\n")
	fmt.Fprintf(b, "title: %s\n", yamlString(title))

	if description != "" {
		fmt.Fprintf(b, "description: %s\n", yamlString(description))
	}

	if order > 0 {
		fmt.Fprintf(b, "sidebar:\n  order: %d\n", order)
	}

	b.WriteString("---\n\n" + marker + "\n\n")
}

// yamlString quotes s as JSON, which YAML reads as a double-quoted string.
func yamlString(s string) string {
	q, _ := json.Marshal(s)
	return string(q)
}

// prose makes text from the code safe as Markdown: "<token>" would be taken for HTML.
func prose(s string) string {
	return strings.NewReplacer("<", "&lt;", ">", "&gt;").Replace(s)
}

// cell makes text safe inside a Markdown table cell.
func cell(s string) string {
	return strings.ReplaceAll(strings.ReplaceAll(prose(s), "|", `\|`), "\n", " ")
}

// firstSentence is s up to the first full stop that ends a sentence: one followed by a
// capital letter, and not part of "e.g." or "i.e.".
func firstSentence(s string) string {
	for i := 0; i+2 < len(s); i++ {
		if s[i] != '.' || s[i+1] != ' ' || s[i+2] < 'A' || s[i+2] > 'Z' {
			continue
		}

		if before := strings.ToLower(s[:i]); strings.HasSuffix(before, "e.g") || strings.HasSuffix(before, "i.e") {
			continue
		}

		return s[:i+1]
	}

	return s
}

// paramLabel names a setting as its table does: **Label** (`name`).
func paramLabel(t engine.NodeType, name string) string {
	for _, p := range t.Params {
		if p.Name == name && p.Label != "" {
			return "**" + p.Label + "** (`" + name + "`)"
		}
	}

	return "`" + name + "`"
}

func portList(names []string) string {
	if len(names) == 0 {
		return "none"
	}

	return codes(names)
}

func codes(items []string) string {
	out := make([]string, len(items))
	for i, s := range items {
		out[i] = "`" + s + "`"
	}

	return strings.Join(out, ", ")
}

func defaultOf(v any) string {
	switch d := v.(type) {
	case nil:
		return ""
	case []string:
		return codes(d)
	case []any:
		parts := make([]string, len(d))
		for i, e := range d {
			parts[i] = fmt.Sprint(e)
		}

		return codes(parts)
	}

	return "`" + cell(fmt.Sprint(v)) + "`"
}

// anchor is the id Starlight gives a heading: lower case, spaces as dashes.
func anchor(heading string) string {
	return strings.ReplaceAll(strings.ToLower(heading), " ", "-")
}

func yesNo(b bool) string {
	if b {
		return "yes"
	}

	return "no"
}

func nonEmpty(items []string) []string {
	return slices.DeleteFunc(items, func(s string) bool { return s == "" })
}

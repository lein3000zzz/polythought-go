package main

import (
	"encoding/json"
	"fmt"
	"strings"
	"time"

	"github.com/lein3000zzz/polythought-go/internal/config"
	"github.com/lein3000zzz/polythought-go/internal/core/services/settings"
)

// exampleConfigPath is where the example config file goes, from the repository's root.
const exampleConfigPath = "configs/polythought.example.yml"

// exampleConfig is a config file with every value it may hold, commented out at its
// default, and what each is (D70).
func exampleConfig(bootstrap []config.BootstrapKey, specs []settings.Spec) string {
	var b strings.Builder

	b.WriteString(`# Polythought's config file (D69). Copy this file to configs/polythought.yml, where the
# server looks for it, or name another with --config or POLYTHOUGHT_CONFIG. Every value is
# optional here and shown at its default; an environment variable wins over it.
#
# A setting set here is locked on the Config page, as one set in the environment is: an
# admin changes the others there. Secrets are better kept in the environment.
#
# Generated by ` + "`make docs-gen`" + ` from the code. Do not edit: change the code and regenerate.
`)

	type value struct{ key, description, env, def string }

	// One heading for each first part of the keys, in the order they first come: the
	// bootstrap values, then the settings. YAML takes a key once.
	var order []string

	byGroup := map[string][]value{}

	add := func(v value) {
		top, _, _ := strings.Cut(v.key, ".")
		if _, ok := byGroup[top]; !ok {
			order = append(order, top)
		}

		byGroup[top] = append(byGroup[top], v)
	}

	for _, k := range bootstrap {
		add(value{k.Key, k.Description, k.Env, yamlText(k.Default)})
	}

	for _, s := range specs {
		description := s.Description
		if s.Kind == settings.KindEnum {
			description += " One of " + strings.Join(s.Options, ", ") + "."
		}

		add(value{s.Key, description, s.EnvName(), yamlValue(s.Default)})
	}

	for _, top := range order {
		fmt.Fprintf(&b, "\n%s:\n", top)

		for _, v := range byGroup[top] {
			entry(&b, v.key, v.description, v.env, v.def)
		}
	}

	return b.String()
}

// entry writes one value, commented out, with what it is above it.
func entry(b *strings.Builder, key, description, env, value string) {
	_, name, _ := strings.Cut(key, ".")

	b.WriteString("\n")

	// A line break in the description keeps what follows whole, like a command.
	for _, paragraph := range strings.Split(description+"\nEnvironment: "+env+".", "\n") {
		for _, line := range wrap(paragraph, 84) {
			fmt.Fprintf(b, "  # %s\n", line)
		}
	}

	fmt.Fprintf(b, "  # %s: %s\n", name, value)
}

// yamlValue writes a setting's default as YAML: JSON is YAML, and durations are text.
func yamlValue(v any) string {
	if d, ok := v.(time.Duration); ok {
		v = settings.FormatDuration(d)
	}

	out, _ := json.Marshal(v)

	return string(out)
}

// yamlText writes a bootstrap default, text as the environment takes it.
func yamlText(v string) string {
	if v == "true" || v == "false" {
		return v
	}

	out, _ := json.Marshal(v)

	return string(out)
}

// wrap breaks text into lines of at most width characters, at spaces.
func wrap(text string, width int) []string {
	var lines []string

	line := ""

	for _, word := range strings.Fields(text) {
		if line != "" && len(line)+1+len(word) > width {
			lines = append(lines, line)
			line = ""
		}

		if line != "" {
			line += " "
		}

		line += word
	}

	return append(lines, line)
}

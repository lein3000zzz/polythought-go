// Command pytypes writes the Python SDK's types from the API's spec, api/openapi.json: a
// TypedDict for each schema, so what the SDK reads and sends is checked by mypy. Run it
// with make sdk-python-types; a test fails while they are stale.
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"log"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
)

const (
	specPath = "api/openapi.json"
	outPath  = "sdk/python/src/polythought/types.py"
)

func main() {
	spec, err := os.ReadFile(specPath)
	if err != nil {
		log.Fatal(err)
	}

	out, err := Generate(spec)
	if err != nil {
		log.Fatal(err)
	}

	if err := os.WriteFile(outPath, out, 0o644); err != nil { //nolint:gosec // a source file, read by all
		log.Fatal(err)
	}
}

// schema is as much of a JSON Schema as the spec uses.
type schema struct {
	Ref                  string             `json:"$ref"`
	Type                 any                `json:"type"`
	Description          string             `json:"description"`
	Properties           map[string]*schema `json:"properties"`
	Required             []string           `json:"required"`
	Items                *schema            `json:"items"`
	AdditionalProperties json.RawMessage    `json:"additionalProperties"`
	Enum                 []any              `json:"enum"`
	AllOf                []*schema          `json:"allOf"`
}

type document struct {
	Components struct {
		Schemas map[string]*schema `json:"schemas"`
	} `json:"components"`
}

var identifier = regexp.MustCompile(`^[A-Za-z_][A-Za-z0-9_]*$`)

// pythonKeywords are those a field cannot be named in a class's body.
var pythonKeywords = map[string]bool{
	"False": true, "None": true, "True": true, "and": true, "as": true, "assert": true, "async": true, "await": true,
	"break": true, "class": true, "continue": true, "def": true, "del": true, "elif": true, "else": true, "except": true,
	"finally": true, "for": true, "from": true, "global": true, "if": true, "import": true, "in": true, "is": true,
	"lambda": true, "nonlocal": true, "not": true, "or": true, "pass": true, "raise": true, "return": true, "try": true,
	"while": true, "with": true, "yield": true,
}

// className is a schema's name as a Python class: the last part of a dotted one, its first
// letter capital.
func className(name string) string {
	if i := strings.LastIndex(name, "."); i >= 0 {
		name = name[i+1:]
	}

	name = regexp.MustCompile(`[^A-Za-z0-9_]`).ReplaceAllString(name, "_")

	return strings.ToUpper(name[:1]) + name[1:]
}

// Generate is the Python module of the spec's types.
func Generate(spec []byte) ([]byte, error) {
	var doc document
	if err := json.Unmarshal(spec, &doc); err != nil {
		return nil, fmt.Errorf("pytypes: %w", err)
	}

	names := make([]string, 0, len(doc.Components.Schemas))
	classes := map[string]string{}

	for name := range doc.Components.Schemas {
		names = append(names, name)

		c := className(name)
		if other, ok := classes[c]; ok {
			return nil, fmt.Errorf("pytypes: %s and %s are both %s in Python", other, name, c)
		}

		classes[c] = name
	}

	slices.SortFunc(names, func(a, b string) int { return strings.Compare(className(a), className(b)) })

	g := gen{refs: map[string]string{}}
	for _, name := range names {
		g.refs["#/components/schemas/"+name] = className(name)
	}

	var b bytes.Buffer

	b.WriteString(`"""The API's types, as TypedDicts: what Polythought answers and takes.

Generated by ` + "`make sdk-python-types`" + ` from api/openapi.json. Do not edit: change the API
and generate them again.
"""

from __future__ import annotations

from typing import Any, Literal, TypedDict

from typing_extensions import NotRequired

__all__ = [
`)

	for _, name := range names {
		fmt.Fprintf(&b, "    %q,\n", className(name))
	}

	b.WriteString("]\n")

	for _, name := range names {
		b.WriteString("\n\n")
		g.class(&b, className(name), doc.Components.Schemas[name])
	}

	return b.Bytes(), nil
}

type gen struct {
	refs map[string]string
}

// class writes one schema as a TypedDict: in a class's body where every field may be named
// there, else in the functional form.
func (g gen) class(b *bytes.Buffer, name string, s *schema) {
	fields := make([]string, 0, len(s.Properties))
	for f := range s.Properties {
		fields = append(fields, f)
	}

	slices.Sort(fields)

	functional := false

	for _, f := range fields {
		if !identifier.MatchString(f) || pythonKeywords[f] {
			functional = true
		}
	}

	typ := func(f string) string {
		t := g.typeOf(s.Properties[f])
		if !slices.Contains(s.Required, f) {
			t = "NotRequired[" + t + "]"
		}

		return t
	}

	if functional {
		fmt.Fprintf(b, "%s = TypedDict(\n    %q,\n    {\n", name, name)

		for _, f := range fields {
			fmt.Fprintf(b, "        %s: %q,\n", strconv.Quote(f), typ(f))
		}

		b.WriteString("    },\n)\n")

		if s.Description != "" {
			fmt.Fprintf(b, "%s.__doc__ = %s\n", name, strconv.Quote(oneLine(s.Description)))
		}

		return
	}

	fmt.Fprintf(b, "class %s(TypedDict):\n", name)

	if s.Description != "" {
		fmt.Fprintf(b, "    %s\n", docstring(s.Description))
	}

	if len(fields) == 0 && s.Description == "" {
		b.WriteString("    pass\n")
		return
	}

	for _, f := range fields {
		if d := s.Properties[f].Description; d != "" {
			for _, line := range wrap(oneLine(d), 92) {
				fmt.Fprintf(b, "    # %s\n", line)
			}
		}

		fmt.Fprintf(b, "    %s: %s\n", f, typ(f))
	}
}

// typeOf is a schema's Python type.
func (g gen) typeOf(s *schema) string {
	if s == nil {
		return "Any"
	}

	if s.Ref != "" {
		if c, ok := g.refs[s.Ref]; ok {
			return c
		}

		return "Any"
	}

	if len(s.AllOf) == 1 {
		return g.typeOf(s.AllOf[0])
	}

	t, _ := s.Type.(string)

	switch t {
	case "string":
		if len(s.Enum) > 0 {
			return literal(s.Enum)
		}

		return "str"
	case "integer":
		return "int"
	case "number":
		return "float"
	case "boolean":
		return "bool"
	case "array":
		return "list[" + g.typeOf(s.Items) + "]"
	case "object":
		if len(s.AdditionalProperties) > 0 && string(s.AdditionalProperties) != "false" && string(s.AdditionalProperties) != "true" {
			var v schema
			if err := json.Unmarshal(s.AdditionalProperties, &v); err == nil {
				return "dict[str, " + g.typeOf(&v) + "]"
			}
		}

		return "dict[str, Any]"
	default:
		return "Any"
	}
}

func literal(values []any) string {
	parts := make([]string, 0, len(values))
	for _, v := range values {
		if s, ok := v.(string); ok {
			parts = append(parts, strconv.Quote(s))
		}
	}

	if len(parts) == 0 {
		return "str"
	}

	return "Literal[" + strings.Join(parts, ", ") + "]"
}

// planRefs are references to the project's own planning, like (D398) or (A16, D403): no
// help to whoever reads the types.
var planRefs = regexp.MustCompile(`\s*\((?:[ADPR]\d{1,3}(?:,\s*)?)+\)`)

// oneLine is a description on one line, without plan references.
func oneLine(s string) string {
	return strings.Join(strings.Fields(planRefs.ReplaceAllString(s, "")), " ")
}

// docstring is a class's description as its docstring, wrapped.
func docstring(s string) string {
	lines := wrap(strings.ReplaceAll(oneLine(s), `"""`, `'''`), 88)
	if len(lines) == 1 {
		return `"""` + lines[0] + `"""`
	}

	return `"""` + strings.Join(lines, "\n    ") + "\n    " + `"""`
}

// wrap breaks s into lines of at most width, at spaces.
func wrap(s string, width int) []string {
	var (
		lines []string
		line  string
	)

	for w := range strings.FieldsSeq(s) {
		if line != "" && len(line)+1+len(w) > width {
			lines = append(lines, line)
			line = w

			continue
		}

		if line != "" {
			line += " "
		}

		line += w
	}

	if line != "" {
		lines = append(lines, line)
	}

	return lines
}

    # a decimal, true or false, or an address, text with options being one of a few choices. Only
    # the whole table takes an expression.
    columns: NotRequired[list[ParamSpec]]
    # CredentialTypes are the kinds of credential a credential param takes: one of the user's of
    # any of them.
    credentialTypes: NotRequired[list[str]]
    default: NotRequired[Any]
    description: NotRequired[str]
    # Field marks a string, or each element of a list, as a path to a field of the items the node
    # receives, like spread or outcomes.0.price. FieldKinds, when present, are the kinds that
    # field may be.
    field: NotRequired[bool]
    fieldKinds: NotRequired[list[Literal["text", "number", "decimal", "bool", "time", "list", "object", "any"]]]
    # Input, for a field, is the input port whose items it names; absent for main.
    input: NotRequired[str]
    kind: Literal["string", "number", "decimal", "bool", "list", "duration", "wallet", "tokens", "address", "table", "credential", "code", "dataset", "model"]
    label: NotRequired[str]
    # ModelsOf, on text, names the credential param whose key's models it suggests:
    # /credentials/{id}/models lists them. Any other name can still be typed.
    modelsOf: NotRequired[str]
    # Multiline text is several lines, a prompt, say.
    multiline: NotRequired[bool]
    name: str
    # Options are the allowed values of a string, or of each element of a list.
    options: NotRequired[list[str]]
    required: bool
    # Sensitive values, like a webhook URL, are personal: sharing leaves them out.
    sensitive: NotRequired[bool]



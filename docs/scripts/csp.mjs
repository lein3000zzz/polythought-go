// Writes the docs' Content-Security-Policy for Caddy, after `astro build`.
//
// The app allows scripts from its own origin only. Starlight puts a few small scripts
// inline (the theme, the sidebar), so the docs allow exactly those, by hash, and nothing
// else inline. Search (Pagefind) compiles WebAssembly, which needs 'wasm-unsafe-eval';
// it does not allow eval() of JavaScript.
import { createHash } from 'node:crypto'
import { readFile, readdir, writeFile } from 'node:fs/promises'
import { join } from 'node:path'

const dist = new URL('../dist/', import.meta.url).pathname
const out = new URL('../csp.caddy', import.meta.url).pathname

const inlineScript = /<script(?<attrs>[^>]*)>(?<body>[\s\S]*?)<\/script>/g
// Event handler attributes, like onclick="…", cannot be allowed by hash.
const handlerAttribute = /<[a-z][^>]*\son[a-z]+\s*=/i

const hashes = new Set()
const problems = []

for (const file of await htmlFiles(dist)) {
  const html = await readFile(file, 'utf8')

  for (const { groups } of html.matchAll(inlineScript)) {
    if (/\ssrc\s*=/.test(groups.attrs)) continue
    hashes.add(`'sha256-${createHash('sha256').update(groups.body).digest('base64')}'`)
  }

  if (handlerAttribute.test(html)) problems.push(`${file}: an inline event handler`)
}

if (problems.length > 0) {
  console.error(`csp: the CSP would block these:\n${problems.join('\n')}`)
  process.exit(1)
}

const policy = [
  "default-src 'self'",
  `script-src 'self' 'wasm-unsafe-eval' ${[...hashes].sort().join(' ')}`,
  "style-src 'self' 'unsafe-inline'",
  "img-src 'self' data:",
  "font-src 'self'",
  "connect-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'self'",
  "frame-ancestors 'none'",
].join('; ')

await writeFile(
  out,
  `# Generated by docs/scripts/csp.mjs from the built pages. Do not edit.\n` +
    `header Content-Security-Policy "${policy}"\n`,
)

console.log(`csp: ${hashes.size} inline scripts allowed by hash, written to csp.caddy`)

async function htmlFiles(dir) {
  const entries = await readdir(dir, { withFileTypes: true, recursive: true })

  return entries.filter((e) => e.isFile() && e.name.endsWith('.html')).map((e) => join(e.parentPath, e.name))
}

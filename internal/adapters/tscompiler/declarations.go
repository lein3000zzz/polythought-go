// The SDK's declarations, as tsc makes them (make sdk-types).
//
//go:embed sdk/types/sdk.d.ts
var sdkDeclarations string

// indexDeclarations is the package's entry: what code imports from @polythought/sdk.
const indexDeclarations = `// The types of @polythought/sdk: the SDK's, and every node type's settings and items.
export * from "./sdk";
export * from "./nodes";
`

// Declarations are the TypeScript declarations code is written against, as the files of
// the @polythought/sdk package an editor loads: index.d.ts, which exports the rest;
// sdk.d.ts, the SDK's; and nodes.d.ts, the settings and items of every node type in types.
func Declarations(types []engine.TypeInfo) []ports.CodeFile {
	return []ports.CodeFile{
		{Path: "index.d.ts", Content: indexDeclarations},
		{Path: "sdk.d.ts", Content: sdkDeclarations},
		{Path: "nodes.d.ts", Content: NodeDeclarations(types)},
	}
}

const nodesHeader = `// Generated by Polythought from its node types: the settings each takes and the items
// it sends on. Do not edit.

import type { Json } from "./sdk";

/** An exact decimal as text, like "0.0200". Do arithmetic with dec(), never as a float. */
export type DecimalText = string;

/** A time as RFC 3339 text, like "2026-10-15T12:00:00Z". */
export type TimeText = string;

/** A duration, like "30s", "5m" or "1h30m". */
export type DurationText = string;

/** A setting's value worked out per item: {{ }} around an expression, like "{{ params.max }}". */
export type Expression = ` + "`{{${string}}}`" + `;
`

// NodeDeclarations declares, for every node type, its settings and the items it sends
// on, and NodeTypes, which names them by type.
func NodeDeclarations(types []engine.TypeInfo) string {
	sorted := slices.Clone(types)
	slices.SortFunc(sorted, func(a, b engine.TypeInfo) int { return strings.Compare(a.Name, b.Name) })

	var b strings.Builder

	b.WriteString(nodesHeader)

	for _, t := range sorted {
		writeSettings(&b, t)
		writeItem(&b, t)
	}

	b.WriteString("\n/**\n * Every node type by name: its settings, and the items it sends on. \"received\" means\n" +
		" * the items it was given, as they are; \"picked\", those with only the fields its\n" +
		" * settings name. Then whether it starts workflows, and the names of its input and\n" +
		" * output ports; a type whose ports a setting makes takes any name beside its own.\n" +
		" */\nexport interface NodeTypes {\n")

	for _, t := range sorted {
		items := "Json"

		switch it := t.Items; {
		case it == nil:
		case it.Passed:
			items = `"received"`
		case it.Picked != "":
			items = `"picked"`
		default:
			items = TypeName(t.Name) + "Item"
		}

		outputs := portNames(t.Outputs)
		if t.OutputsParam != "" {
			outputs = strings.TrimPrefix(outputs+" | (string & {})", "never | ")
		}

		fmt.Fprintf(&b, "    %s: {\n        settings: %sSettings;\n        items: %s;\n        trigger: %t;\n        inputs: %s;\n        outputs: %s;\n    };\n",
			quote(t.Name), TypeName(t.Name), items, t.Trigger, portNames(t.Inputs), outputs)
	}

	b.WriteString("}\n")

	return b.String()
}

// portNames is a union of port names, or never for none.
func portNames(names []string) string {
	if len(names) == 0 {
		return "never"
	}

	quoted := make([]string, len(names))
	for i, n := range names {
		quoted[i] = quote(n)
	}

	return strings.Join(quoted, " | ")
}

func writeSettings(b *strings.Builder, t engine.TypeInfo) {
	name := TypeName(t.Name) + "Settings"
	fmt.Fprintf(b, "\n/** The settings of %s (%s). */\n", label(t), t.Name)

	if len(t.Params) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, never>;\n", name)
		return
	}

	fmt.Fprintf(b, "export interface %s {\n", name)

	for _, p := range t.Params {
		doc := []string{p.Description}

		switch {
		case p.Field:
			doc = append(doc, "A field of the items it receives.")
		case p.Kind == engine.ParamWallet:
			doc = append(doc, "The ID of one of your wallets.")
		case p.Kind == engine.ParamCredential:
			doc = append(doc, fmt.Sprintf("The ID of one of your credentials of type %s.", p.CredentialType))
		case p.Kind == engine.ParamTokens:
			doc = append(doc, "Outcome token IDs.")
		case p.Kind == engine.ParamAddress:
			doc = append(doc, addressDoc)
		case p.Kind == engine.ParamTable:
			doc = append(doc, "A table: a row each.")
		}

		writeDoc(b, "    ", strings.TrimSpace(strings.Join(doc, " ")), defaultTag(p)...)

		typ := paramType(p)
		if !t.Trigger && engine.TakesExpressions(t.NodeType, p) && !strings.HasSuffix(typ, "string") {
			typ += " | Expression" // text takes {{ }} as it is
		}

		fmt.Fprintf(b, "    %s%s: %s;\n", property(p.Name), optionalMark(p), typ)
	}

	b.WriteString("}\n")
}

const addressDoc = "A Polygon address: 0x and 40 hex digits."

func optionalMark(p engine.ParamSpec) string {
	if p.Required && p.Default == nil {
		return ""
	}

	return "?"
}

func defaultTag(p engine.ParamSpec) []string {
	if p.Default == nil {
		return nil
	}

	d, err := json.Marshal(p.Default)
	if err != nil {
		return nil
	}

	return []string{"@default " + string(d)}
}

// rowType is the type of a table's rows: an object of its cells, each as its column
// says, plain values (D82).
func rowType(p engine.ParamSpec) string {
	var b strings.Builder

	b.WriteString("{\n")

	for _, c := range p.Columns {
		doc := c.Description
		if c.Kind == engine.ParamAddress {
			doc = strings.TrimSpace(doc + " " + addressDoc)
		}

		writeDoc(&b, "        ", doc, defaultTag(c)...)
		fmt.Fprintf(&b, "        %s%s: %s;\n", property(c.Name), optionalMark(c), paramType(c))
	}

	b.WriteString("    }[]")

	return b.String()
}

func paramType(p engine.ParamSpec) string {
	switch p.Kind {
	case engine.ParamString:
		return union(p.Options, "string")
	case engine.ParamNumber:
		return "number"
	case engine.ParamDecimal:
		return "DecimalText | number"
	case engine.ParamBool:
		return "boolean"
	case engine.ParamList:
		if len(p.Options) > 0 {
			return "(" + union(p.Options, "") + ")[]"
		}

		return "string[]"
	case engine.ParamDuration:
		return "DurationText"
	case engine.ParamTokens:
		return "string[]"
	case engine.ParamTable:
		return rowType(p)
	default: // code, addresses, and wallets and credentials by ID
		return "string"
	}
}

func writeItem(b *strings.Builder, t engine.TypeInfo) {
	it := t.Items
	if it == nil || it.Received() {
		return // NodeTypes says so
	}

	name := TypeName(t.Name) + "Item"
	fmt.Fprintf(b, "\n/** An item %s (%s) sends on. */\n", label(t), t.Name)

	if len(it.Fields) == 0 {
		fmt.Fprintf(b, "export type %s = Record<string, never>;\n", name)
		return
	}

	fmt.Fprintf(b, "export interface %s {\n", name)
	writeFields(b, it.Fields, "    ")
	b.WriteString("}\n")
}

func writeFields(b *strings.Builder, fields []engine.Field, indent string) {
	for _, f := range fields {
		writeDoc(b, indent, f.Description)

		optional := ""
		if f.Optional {
			optional = "?"
		}

		fmt.Fprintf(b, "%s%s%s: %s;\n", indent, property(f.Name), optional, fieldType(f, indent))
	}
}

func fieldType(f engine.Field, indent string) string {
	var t string

	switch f.Kind {
	case engine.FieldText:
		t = union(f.Options, "string")
	case engine.FieldNumber:
		t = "number"
	case engine.FieldDecimal:
		t = "DecimalText"
	case engine.FieldBool:
		t = "boolean"
	case engine.FieldTime:
		t = "TimeText"
	case engine.FieldList:
		t = "Json[]"

		if f.Of != nil {
			elem := fieldType(*f.Of, indent)
			if strings.Contains(elem, " | ") {
				elem = "(" + elem + ")"
			}

			t = elem + "[]"
		}
	case engine.FieldObject:
		var b strings.Builder

		b.WriteString("{\n")
		writeFields(&b, f.Fields, indent+"    ")
		b.WriteString(indent + "}")

		t = b.String()
	default:
		t = "Json"
	}

	if f.Nullable {
		t += " | null"
	}

	return t
}

// writeDoc writes a JSDoc comment of text and tags, if there is any.
func writeDoc(b *strings.Builder, indent, text string, tags ...string) {
	text = strings.ReplaceAll(text, "*/", "*\\/")
	if text == "" && len(tags) == 0 {
		return
	}

	if len(tags) == 0 {
		fmt.Fprintf(b, "%s/** %s */\n", indent, text)
		return
	}

	fmt.Fprintf(b, "%s/**\n", indent)

	if text != "" {
		fmt.Fprintf(b, "%s * %s\n", indent, text)
	}

	for _, tag := range tags {
		fmt.Fprintf(b, "%s * %s\n", indent, strings.ReplaceAll(tag, "*/", "*\\/"))
	}

	fmt.Fprintf(b, "%s */\n", indent)
}

// TypeName is a node type's name in TypeScript: polymarket.priceChange is
// PolymarketPriceChange.
func TypeName(name string) string {
	var b strings.Builder

	for part := range strings.FieldsFuncSeq(name, func(r rune) bool { return !unicode.IsLetter(r) && !unicode.IsDigit(r) }) {
		runes := []rune(part)
		runes[0] = unicode.ToUpper(runes[0])
		b.WriteString(string(runes))
	}

	return b.String()
}

func label(t engine.TypeInfo) string {
	if t.Label != "" {
		return t.Label
	}

	return t.Name
}

func union(options []string, otherwise string) string {
	if len(options) == 0 {
		return otherwise
	}

	quoted := make([]string, len(options))
	for i, o := range options {
		quoted[i] = quote(o)
	}

	return strings.Join(quoted, " | ")
}

var identifier = regexp.MustCompile(`^[A-Za-z_$][A-Za-z0-9_$]*$`)

func property(name string) string {
	if identifier.MatchString(name) {
		return name
	}

	return quote(name)
}

func quote(s string) string {
	b, _ := json.Marshal(s)
	return string(b)
}
